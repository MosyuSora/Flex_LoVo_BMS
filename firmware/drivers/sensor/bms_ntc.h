#ifndef BMS_NTC_H
#define BMS_NTC_H

#include <stdint.h>

/*
 * ============================================================================
 * NTC 热敏电阻 -> 温度换算(与具体 AFE 芯片解耦的传感器知识)
 * ============================================================================
 *
 * 职责边界(SRP):
 *   - AFE 芯片驱动(bq769x0_core 等)只负责把 TS 通道的分压读成 mV
 *     ——那是"芯片怎么采 ADC"的知识。
 *   - 本模块负责"这颗热敏电阻怎么把 mV 变成温度",以及开路/短路诊断
 *     ——那是"传感器 + 板级分压"的知识。
 *
 * 于是换热敏电阻型号(不同 R25 / B 值)或换分压网络,只动本模块,
 * 不碰任何芯片驱动。这正是把传感器特性从芯片传输里剥出来的意义。
 *
 * 板级分压事实(BoardFacts):10k 上拉到 3.3V,NTC 对地;
 * 热敏电阻 10k@25C、B=3380。曲线用离线预制表(避免片上 log/浮点)。
 */

/*
 * TS 分压(mV)-> 温度(0.01C)。
 * 返回 0 并写温度 = 读数可信;返回 -ERANGE 且温度写 0 = NTC 开路/短路
 * (调用方据此清 valid 位,不要采信温度值本身)。
 * 返回 -EINVAL = 出参为 NULL。本函数可重入、线程安全(无静态可变状态)。
 */
int bms_ntc_mv_to_cdeg(uint16_t ts_mv, int16_t *cdeg_out);

#endif /* BMS_NTC_H */
